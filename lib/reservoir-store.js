"use strict";
// Single source of truth for area reservoirs = the Supabase `trip_reservoirs`
// table (column `structured` holds the canonical reservoir object; `area_html`
// is the site rendering). Everything reads and writes through here:
//   - pullReservoir(s): Supabase -> refresh the local JSON cache -> return data.
//   - saveReservoir:    object -> Supabase (source) + local cache + wiki mirror.
//   - readCache/listAreas: fast local/offline access.
// The local data/trip-reservoir/<area>.json files are a derived
// read-through cache (fast sync reads for the itinerary builder + offline
// fallback), NOT an independent source. The wiki page trip_reservoir_<area>
// is a rendered mirror, regenerated by saveReservoir from the same object. So a
// change made once flows to the builder, the site, and the wiki together.

const fs = require("node:fs");
const path = require("node:path");
const { request } = require("./supabase-rest.js");
const { renderReservoirHtml, renderReservoirWiki } = require("./reservoir-render.js");

// lib -> data/trip-reservoir (same dir the itinerary builder reads).
const RES_DIR = path.join(__dirname, "..", "data", "trip-reservoir");

function cachePath(area) {
  return path.join(RES_DIR, `${area}.json`);
}
function writeCache(area, reservoir) {
  try {
    fs.mkdirSync(RES_DIR, { recursive: true });
    fs.writeFileSync(cachePath(area), JSON.stringify(reservoir, null, 2));
  } catch { /* cache write is best-effort */ }
}
function readCache(area) {
  try {
    return JSON.parse(fs.readFileSync(cachePath(area), "utf8"));
  } catch {
    return null;
  }
}

// Supabase-first read; refreshes the local cache on success; falls back to the
// cache (last-known-good) if Supabase is unreachable, so a build never breaks.
async function pullReservoir(area) {
  try {
    const rows = await request(
      `/rest/v1/trip_reservoirs?area=eq.${encodeURIComponent(area)}&select=structured`,
      {}
    );
    const s = rows && rows[0] && rows[0].structured;
    if (s) {
      writeCache(area, s);
      return s;
    }
  } catch {
    /* offline / error -> fall back to cache below */
  }
  return readCache(area);
}

async function pullReservoirs(areas) {
  const out = {};
  for (const a of [...new Set((areas || []).filter(Boolean))]) {
    out[a] = await pullReservoir(a);
  }
  return out;
}

// Areas known to the source of truth (falls back to the cache dir offline).
async function listAreas() {
  try {
    const rows = await request(`/rest/v1/trip_reservoirs?select=area&order=area`, {});
    if (rows && rows.length) return rows.map((r) => r.area);
  } catch {
    /* fall through */
  }
  try {
    return fs.readdirSync(RES_DIR).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, ""));
  } catch {
    return [];
  }
}

// Write a reservoir to the source of truth and regenerate every view from it:
// Supabase (structured + rendered area_html), the local cache, and the wiki
// mirror. wikiSave lets the caller supply a save fn; if omitted we lazily load
// the mini wiki-store (non-fatal when unavailable, e.g. off-mini).
async function saveReservoir(area, reservoir, { wikiSave } = {}) {
  const row = {
    area,
    label: reservoir.label || area,
    date_range: reservoir.date_range || null,
    area_html: renderReservoirHtml(reservoir),
    structured: reservoir,
    updated_at: new Date().toISOString(),
  };
  await request(`/rest/v1/trip_reservoirs?on_conflict=area`, {
    method: "POST",
    body: [row],
    prefer: "resolution=merge-duplicates,return=minimal",
  });
  writeCache(area, reservoir);
  // Wiki mirror — rendered from the SAME object, so it can't drift from Supabase.
  try {
    // wikiSave is a FUNCTION. the mark-done sweep passed `true`, which
    // sailed through this `||`, threw "save is not a function" on the next
    // line, and was swallowed by the catch below — so the nightly done-marking
    // pass never once updated the wiki mirror. Supabase and the site were
    // right; only the wiki drifted, silently, because the catch is
    // deliberately non-fatal. Ignore a non-function so a bad caller degrades
    // to the default instead of disabling the mirror.
    const custom = typeof wikiSave === "function" ? wikiSave : null;
    const save = custom || ((id, body) => require("./wiki-store.js").savePage(id, body, { editedBy: "reservoir-store" }));
    save(`trip_reservoir_${area}`, renderReservoirWiki(reservoir));
  } catch {
    /* wiki unavailable (off-mini / no wiki-store) — non-fatal */
  }
}

module.exports = { pullReservoir, pullReservoirs, readCache, listAreas, saveReservoir, RES_DIR };
